		/// <summary>
		/// Сокращает наименование должности по словарю до допустимой длины.
		/// Если после сокращений строка всё ещё длиннее <see cref="_maxPositionLength"/>,
		/// обрезает её по границе слова.
		/// </summary>
		public static string ToShortPosition(this string position)
		{
			if(string.IsNullOrWhiteSpace(position))
			{
				return position ?? string.Empty;
			}

			var result = position;

			foreach(var (full, shortForm) in _positionAbbreviations)
			{
				result = ReplaceWord(result, full, shortForm);
			}

			while(result.Contains("  "))
			{
				result = result.Replace("  ", " ");
			}

			result = result.Trim();

			if(result.Length > _maxPositionLength)
			{
				var cutoff = result.LastIndexOf(' ', _maxPositionLength - 1);
				if(cutoff <= 0)
				{
					cutoff = _maxPositionLength;
				}

				result = result.Substring(0, cutoff).TrimEnd(' ', '.', ',');
			}

			return result;
		}

		private static string ReplaceWord(string source, string word, string replace)
		{
			var pattern = $@"\b{Regex.Escape(word)}\b";
			return Regex.Replace(source, pattern, replace, RegexOptions.IgnoreCase);
		}
