using System.ComponentModel.DataAnnotations;

namespace Vodovoz.Core.Domain.Edo
{
	/// <summary>
	/// Причина снятия отклонения документооборота ЭДО.
	/// Позволяет отличить документообороты, по которым отклонение действительно
	/// перестало быть актуальным, от тех, где оно снято по внешней причине:
	/// например, потому что по задаче зарегистрировали проблему
	/// </summary>
	public enum EdoDeviationResolveReason
	{
		/// <summary>
		/// Валидатор перестал срабатывать: документооборот пошел дальше.
		/// Единственная причина, по которой отклонение считается решившимся само
		/// </summary>
		[Display(Name = "Условие перестало выполняться")]
		ConditionGone,

		/// <summary>
		/// Задача завершена или отменена
		/// </summary>
		[Display(Name = "Задача завершена или отменена")]
		TaskFinished,

		/// <summary>
		/// По задаче зарегистрирована проблема:
		/// причина известна и случай перешел в журнал проблем
		/// </summary>
		[Display(Name = "Зарегистрирована проблема")]
		ProblemRegistered,

		/// <summary>
		/// По заявке создана задача ЭДО
		/// </summary>
		[Display(Name = "По заявке создана задача")]
		TaskCreated,

		/// <summary>
		/// Тип отклонения выключен или удален из справочника описаний отклонений
		/// </summary>
		[Display(Name = "Проверка отключена")]
		ValidatorDisabled,

		/// <summary>
		/// Задача или заявка, по которой зафиксировано отклонение, не найдена
		/// </summary>
		[Display(Name = "Задача или заявка не найдены")]
		EntityNotFound
	}
}
