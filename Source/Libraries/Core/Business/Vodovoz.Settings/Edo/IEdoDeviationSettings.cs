using System;

namespace Vodovoz.Settings.Edo
{
	/// <summary>
	/// Настройки сервиса мониторинга отклонений документооборота ЭДО.
	/// Таймауты отклонений здесь не хранятся: они лежат в справочнике
	/// описаний отклонений, по одной записи на тип
	/// </summary>
	public interface IEdoDeviationSettings
	{
		/// <summary>
		/// Признак того, что воркеры мониторинга отклонений выполняют работу.
		/// Читается на каждом проходе, поэтому выключение действует
		/// без перезапуска сервиса, с задержкой на время кеширования настройки
		/// </summary>
		bool IsEnabled { get; }

		/// <summary>
		/// Интервал работы воркера регистрации отклонений
		/// </summary>
		TimeSpan RegistrationWorkerInterval { get; }

		/// <summary>
		/// Интервал работы воркера снятия отклонений
		/// </summary>
		TimeSpan ResolvingWorkerInterval { get; }

		/// <summary>
		/// Количество задач, обрабатываемых за один проход
		/// </summary>
		int BatchSize { get; }

		/// <summary>
		/// Дата, с которой отслеживается результат обработки кодов в ГИС МТ.
		/// Отклонения этой группы не заводятся по заказам, доставленным раньше нее:
		/// по документообороту, завершенному до появления статуса прослеживаемости в учете,
		/// результат ГИС МТ уже не придет
		/// </summary>
		DateTime GisMtTrackingStartDate { get; }
	}
}
