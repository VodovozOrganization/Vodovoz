namespace Notifications.Core
{
	/// <summary>
	/// Уведомление, которое не отправляется повторно.
	/// По ключу дедупликации публикатор уведомлений пропускает уже отправленное уведомление,
	/// а по ключу агрегата в одной транзакции оставляет только последнее уведомление о нём
	/// </summary>
	public interface IDeduplicatedNotification
	{
		/// <summary>
		/// Ключ агрегата, о котором уведомление (например, номер заказа или тип уведомления ЭДО)
		/// </summary>
		string GetAggregateKey();

		/// <summary>
		/// Ключ дедупликации: одинаковый у уведомлений, которые считаются повтором
		/// </summary>
		/// <returns>Ключ или пустая строка, если уведомление можно отправлять повторно</returns>
		string GetDeduplicationKey();
	}
}
